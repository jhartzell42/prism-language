# Writes bignum_vectors.inc: (a, b, a+b, a-b, a*b, a // b, a % b) with Python's floored
# division, over operands built to reach Knuth D's corrections (limbs 0, 1, 2^31,
# 2^31-1, 2^32-1) and random ones. Run: python3 gen_bignum_vectors.py > bignum_vectors.inc
import random

random.seed(47)
SPECIAL = [0, 1, 2**31, 2**31 - 1, 2**32 - 1, 2**32 - 2]

def operand():
    n = random.choice([1, 1, 2, 2, 3, 4, 5, 8, 13])
    limbs = [random.choice(SPECIAL) if random.random() < 0.5 else random.getrandbits(32) for _ in range(n)]
    v = sum(l << (32 * i) for i, l in enumerate(limbs))
    return -v if random.random() < 0.4 else v

cases = [(2**64, 2**32 + 1), (2**128 - 1, 2**64 + 1), (-(2**63), -1), (2**63, -1), (10**40, 7), (-(10**40), 7),
         (10**40, -(10**20) - 3), (2**96 - 1, 2**64 - 1), (2**95, 2**63 + 1), (0, 5), (-7, 2), (7, -2)]
while len(cases) < 400:
    a, b = operand(), operand()
    if b != 0:
        cases.append((a, b))
print("// Generated by gen_bignum_vectors.py: a, b, a+b, a-b, a*b, a/b, a mod b (floored).")
for a, b in cases:
    print('{"%d", "%d", "%d", "%d", "%d", "%d", "%d"},' % (a, b, a + b, a - b, a * b, a // b, a % b))
