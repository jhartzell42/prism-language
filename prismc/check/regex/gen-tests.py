#!/usr/bin/env python3
# Writes tests.prism and tests.expected beside this script from tests/regex/corpus.txt:
# the test module `Check.Regex.Tests`, which holds prismc's dialect check to the same
# corpus both runtimes read (claude/regex-dialect.md). A test module runs under the Test
# World, which reads no file, so the corpus is turned into checks here: every `refuse`
# row's diagnostic, `part@at message`, and every other row's pattern (with its
# replacement, for `replace`) accepted. Run it after the corpus changes:
#
#   python3 -I prismc/check/regex/gen-tests.py
#
# Written by Claude on the claude-self-hosting branch; subject to change.
import os
import re
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", "..", ".."))
corpus = os.path.join(root, "tests", "regex", "corpus.txt")


def field(text):
    """A corpus field as its text, or None for the absent text."""
    if text == "⟨-⟩":
        return None
    if text == "⟨⟩":
        return ""
    def code(m):
        cp = int(m.group(1), 16)
        if 0xD800 <= cp <= 0xDFFF:
            sys.exit(f"a surrogate in the corpus: {text}")
        return chr(cp)
    return re.sub(r"⟨([0-9A-Fa-f]+)⟩", code, text)


def prism_text(t):
    """A Prism text literal holding exactly `t` (Semantics ch. 2, Text)."""
    out = []
    for i, c in enumerate(t):
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "{":
            out.append("\\{")
        elif c == "}":
            out.append("\\}")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif ord(c) < 0x20 or ord(c) == 0x7F:
            out.append("\\u{%x}" % ord(c))
        elif c == ">" and i > 0 and t[i - 1] == "=":
            # A check line holds one `=>`, its own.
            out.append("\\u{3e}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def optional(t):
    return "nil" if t is None else "? " + prism_text(t)


sections = []  # (name, [check line])
name = "literals"
lines = []
seen = set()
for raw in open(corpus, encoding="utf-8"):
    raw = raw.rstrip("\n")
    if raw.startswith("# ---- "):
        if lines:
            sections.append((name, lines))
        title = raw[len("# ---- "):]
        # The first three words of the section's title, as a check's name.
        name = "_".join(re.findall(r"[a-z0-9]+", title.lower())[:3])
        lines = []
        continue
    if raw == "" or raw.startswith("#"):
        continue
    cols = raw.split("\t")
    if len(cols) != 6:
        sys.exit(f"not six fields: {raw}")
    kind, pattern, flags, arg, _input, expected = cols
    pattern, flags = field(pattern), field(flags)
    if kind == "refuse":
        rep = field(arg)
        want = field(expected)
    elif kind == "replace":
        rep = field(arg)
        want = "accepted"
    else:
        rep = None
        want = "accepted"
    key = (pattern, flags, rep)
    if key in seen:
        continue
    seen.add(key)
    lines.append(f"    Refused {prism_text(pattern)}, {prism_text(flags)}, {optional(rep)} => {prism_text(want)}")
if lines:
    sections.append((name, lines))

names = [n for n, _ in sections]
if len(set(names)) != len(names):
    sys.exit(f"two sections share a name: {names}")

with open(os.path.join(here, "tests.prism"), "w", encoding="utf-8") as out:
    out.write("# The test module of `Check.Regex`: the shared corpus, tests/regex/corpus.txt, as\n")
    out.write("# checks. Generated by gen-tests.py beside it, which says why; do not edit by hand.\n")
    out.write("# Written by Claude on the claude-self-hosting branch; subject to change.\n")
    out.write("emit r\n")
    out.write("use Check.Regex.*\n\n")
    out.write("# A pattern, its flags and a replacement as the corpus writes the result: `accepted`,\n")
    out.write("# or the diagnostic `part@at message`.\n")
    out.write("Refused: fn Text, Text, ?Text -> Text\n")
    out.write("fn Refused pattern, flags, ?replacement = match ?RegexRefusal pattern, flags, ?replacement:\n")
    out.write("    nil: \"accepted\"\n")
    out.write("    ? d: \"{d.part}@{d.at} {d.message}\"\n")
    for n, ls in sections:
        out.write(f"\ncheck {n}:\n")
        out.write("\n".join(ls) + "\n")

with open(os.path.join(here, "tests.expected"), "w", encoding="utf-8") as out:
    blocks = []
    for n, ls in sections:
        blocks.append(f"check {n}\n" + "".join(f"{i + 1}: ok\n" for i in range(len(ls))))
    out.write("\n".join(blocks))

print(f"{sum(len(ls) for _, ls in sections)} checks in {len(sections)} blocks")
